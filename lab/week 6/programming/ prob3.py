# 문제   : 람다식을 사용하여 튜플로 이루어진 리스트를 점수 기준으로 정렬한다.
# 설계   :
#   1. (과목, 점수) 튜플들로 리스트를 만든다.
#   2. sorted() 함수의 key에 lambda x: x[1]을 주어 점수(두 번째 값) 기준으로 정렬한다.
#   3. 원래 리스트와 정렬된 리스트를 출력한다.
# ============================================================

a = [('국어', 88), ('수학', 90), ('영어', 99), ('자연', 82)]

b = sorted(a, key=lambda x: x[1])

print("원래의 리스트:")
print(a)
print("정렬된 리스트:")
print(b)
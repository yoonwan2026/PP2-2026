# 문제   : random 모듈의 함수를 사용하여 알파벳 a부터 z 사이에서 랜덤하게 10개의 문자를 출력한다.
# 설계   :
#   1. 알파벳 a~z를 문자열로 만든다.
#   2. 10번 반복하면서 random.choice()로 한 글자씩 뽑는다.
#   3. 뽑은 글자를 이어 붙여 출력한다.
# ============================================================

import random

a = 'abcdefghijklmnopqrstuvwxyz'

b = ''
for i in range(10):
    b = b + random.choice(a)

print(b)
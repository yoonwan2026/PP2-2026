# 문제   : 호출될 때마다 앞의 수에 1을 더하여 반환하는 상한값 없는 제너레이터 함수를 작성한다.
# 설계   :
#   1. my_count(a) 함수에서 while True 무한 반복을 사용한다.
#   2. yield로 현재 값을 돌려주고, 다음 호출 때 1을 더한다.
#   3. 무한히 나오므로 사용하는 쪽에서 for 문과 break로 5개만 출력해 확인한다.
# ============================================================

def my_count(a=0):
    while True:
        yield a
        a = a + 1


for x in my_count(1):
    print(x)
    if x >= 5:   
        break
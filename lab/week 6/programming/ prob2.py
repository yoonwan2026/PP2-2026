# 문제   : eval() 함수로 사용자가 입력한 문자열을 오류 없이 정수나 실수로 변환한다.
# 설계   :
#   1. input()으로 문자열을 입력받는다.
#   2. eval()로 문자열을 숫자로 바꾼다. (10 -> 정수, 10.2 -> 실수)
#   3. 숫자가 아닌 문자열을 입력하면 오류가 나므로 try-except로 처리한다.
#   4. 변환된 값을 출력한다.
# ============================================================

a = input("정수나 실수를 입력하시오: ")

try:
    b = eval(a)
    if type(b) == int or type(b) == float:
        print(b)
    else:
        print("정수나 실수가 아닙니다.")
except:
    print("정수나 실수가 아닙니다.")
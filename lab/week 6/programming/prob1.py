# 문제   : 1부터 100 사이 정수 중 3의 배수의 개수를 리스트 함축과 내장 함수로 구한다.
# 설계   :
#   1. range(1, 101)로 1~100까지 숫자를 만든다.
#   2. 리스트 함축으로 3으로 나누어 떨어지는 수만 모은다.
#   3. 내장 함수 len()으로 리스트의 개수를 센다.
#   4. 결과를 출력한다.
# ============================================================

a = [x for x in range(1, 101) if x % 3 == 0]
b = len(a)
print("3의 배수의 개수 =", b)
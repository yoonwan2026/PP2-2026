# 문제   : 100과 200 사이에서 5개의 짝수 난수를 발생시킨다.
# 설계   :
#   1. range(100, 201, 2)로 100~200 사이의 짝수만 만든다.
#   2. random.sample()로 중복 없이 5개를 뽑는다.
#   3. 리스트를 출력한다.
# ============================================================

import random

a = range(100, 201, 2)

b = random.sample(a, 5)

print(b)
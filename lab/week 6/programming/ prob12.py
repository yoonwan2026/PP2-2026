# 문제   : random 모듈의 함수를 사용하여 7개의 단어 중에서 랜덤하게 3개를 선택하여 출력한다.
# 설계   :
#   1. 7개의 단어로 리스트를 만든다.
#   2. random.sample(리스트, 3)으로 중복 없이 3개를 뽑는다.
#   3. 뽑은 단어를 한 줄로 출력한다.
# ============================================================

import random

a = ['학습', '컴퓨터', '마우스', '키보드', '모니터', '프로그램', '파이썬']

b = random.sample(a, 3)

for x in b:
    print(x, end=' ')
print()